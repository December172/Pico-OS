use crate::kernel::drivers::timer_driver::TimerDriver;
use crate::util::low_level::_poll;
use crate::util::register::Register;

use crate::native::constants::rp2040::resets::*;
use crate::native::constants::rp2040::timer::*;
use crate::native::constants::rp2040::watchdog::*;

pub struct _TimerDriver {
    timehr: Register,
    timelr: Register,
    watchdog_tick: Register,
}

impl TimerDriver for _TimerDriver {
    fn now_tick(&self) -> u64 {
        let low = self.timelr.read();
        let high = self.timehr.read();
        // Combine high bits and low bits
        return ((high as u64) << 32) | (low as u64);
    }

    /// RP2040 quirk: the timer has no clock of its own - its microseconds are
    /// generated by the watchdog tick generator, which divides clk_ref down to
    /// 1us (datasheet 4.6 + 4.7.2). When the chip is reset by a debugger
    /// instead of by the bootrom, nobody else brings this up.
    fn init(&self, ref_freq: u32) -> bool {
        // `ref_freq` is the clk_ref frequency: the tick generator divides clk_ref
        // down to the 1us reference.
        // (Truncating division: a 6.5MHz rosc reference is ~8% off, which is
        // unavoidable since the divider is an integer.)
        self.watchdog_tick.field_set(
            WATCHDOG_TICK_CYCLES_HIGH,
            WATCHDOG_TICK_CYCLES_LOW,
            ref_freq / 1_000_000,
        );

        // configure watchdog first
        self.watchdog_tick.bit_set(WATCHDOG_TICK_ENABLE_BIT, true);
        if !_poll(10_000, || {
            self.watchdog_tick.bit_get(WATCHDOG_TICK_RUNNING_BIT)
        }) {
            return false;
        }

        // give the timer a reset pulse *after* the tick is live
        // otherwise the timer will not notice watchdog
        let reset = Register::new(RESETS_RESET);
        let reset_done = Register::new(RESETS_RESET_DONE);
        reset.bit_set(RESETS_RESET_TIMER_BIT, true);
        reset.bit_set(RESETS_RESET_TIMER_BIT, false);
        if !_poll(10_000, || reset_done.bit_get(RESETS_RESET_DONE_TIMER_BIT)) {
            return false;
        }

        // clear PAUSE / DBGPAUSE *after* the reset pulse
        // the watchdog will continue to run under debugger
        let timer_pause = Register::new(TIMER_PAUSE);
        let timer_dbg_pause = Register::new(TIMER_DBGPAUSE);
        // resume hardware timer
        timer_pause.write(0);
        // TIMER_DBGPAUSE_DBG0_BIT: pause watchdong when core0 is in debug mode
        // TIMER_DBGPAUSE_DBG1_BIT: ... when core1 is in debug mode
        timer_dbg_pause.write(0);
        if timer_dbg_pause.read() != 0 {
            return false;
        }

        // finally prove the counter actually counts
        return _poll(10_000, || self.now_tick() != 0);
    }
}

impl _TimerDriver {
    pub fn new() -> Self {
        Self {
            timehr: Register::new(TIMER_TIMEHR),
            timelr: Register::new(TIMER_TIMELR),
            watchdog_tick: Register::new(WATCHDOG_TICK),
        }
    }
}
