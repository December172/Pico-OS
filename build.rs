#![allow(non_snake_case)]

use std::env;
use std::fs;
use std::path::PathBuf;

use toml::Value;

const FLASH_ORIGIN: u64 = 0x1000_0000;

fn positiveInteger(root: &Value, path: &[&str]) -> u64 {
    let pathName = path.join(".");
    let mut value = root;

    for key in path {
        value = value
            .get(*key)
            .unwrap_or_else(|| panic!("missing Cargo.toml field `{pathName}`"));
    }

    let value = value
        .as_integer()
        .unwrap_or_else(|| panic!("`{pathName}` must be an integer"));

    u64::try_from(value)
        .ok()
        .filter(|value| *value != 0)
        .unwrap_or_else(|| panic!("`{pathName}` must be positive"))
}

fn main() {
    if env::var_os("CARGO_FEATURE_RP2040").is_none() {
        panic!("enable the RP2040 feature");
    }

    let target = env::var("TARGET").expect("Cargo did not provide TARGET");
    if target != "thumbv6m-none-eabi" {
        panic!("RP2040 requires target thumbv6m-none-eabi");
    }

    let manifestPath = PathBuf::from(
        env::var_os("CARGO_MANIFEST_PATH").expect("Cargo did not provide CARGO_MANIFEST_PATH"),
    );

    let manifestText = fs::read_to_string(&manifestPath).expect("failed to read Cargo.toml");
    let manifest: Value = manifestText.parse().expect("failed to parse Cargo.toml");

    let flashMiB = positiveInteger(
        &manifest,
        &["package", "metadata", "pico-os", "flash-size-mb"],
    );
    let userFlashKiB = positiveInteger(
        &manifest,
        &["package", "metadata", "pico-os", "user-flash-size-kb"],
    );

    let flashBytes = flashMiB
        .checked_mul(1024 * 1024)
        .expect("flash size overflow");
    let userFlashBytes = userFlashKiB
        .checked_mul(1024)
        .expect("user flash size overflow");

    assert!(
        userFlashBytes >= 256 && userFlashBytes.is_power_of_two(),
        "user flash size must be a power of two and at least 256 bytes"
    );
    assert!(
        userFlashBytes < flashBytes,
        "user flash must be smaller than physical flash"
    );

    let flashEnd = FLASH_ORIGIN
        .checked_add(flashBytes)
        .expect("flash address overflow");
    let userFlashOrigin = flashEnd - userFlashBytes;

    assert!(
        userFlashOrigin & (userFlashBytes - 1) == 0,
        "user flash origin is not aligned to its MPU region size"
    );

    let kernelFlashBytes = userFlashOrigin - FLASH_ORIGIN;

    let generatedLinker = format!(
        r#"/* Generated by build.rs. Do not edit. */
MEMORY
{{
    FLASH(rx)      : ORIGIN = 0x{FLASH_ORIGIN:08x}, LENGTH = 0x{kernelFlashBytes:x}
    USER_FLASH(rx) : ORIGIN = 0x{userFlashOrigin:08x}, LENGTH = 0x{userFlashBytes:x}
    RAM(rwx)       : ORIGIN = 0x20000000, LENGTH = 256K
    SCRATCH_X(rwx) : ORIGIN = 0x20040000, LENGTH = 4K
    SCRATCH_Y(rwx) : ORIGIN = 0x20041000, LENGTH = 4K
}}

__flash_start = 0x{FLASH_ORIGIN:08x};
__flash_end = 0x{flashEnd:08x};
__user_flash_start = ORIGIN(USER_FLASH);
__user_flash_end = ORIGIN(USER_FLASH) + LENGTH(USER_FLASH);

INCLUDE RP2040.ld
"#
    );

    let outDirectory =
        PathBuf::from(env::var_os("OUT_DIR").expect("Cargo did not provide OUT_DIR"));
    let generatedLinkerPath = outDirectory.join("pico-os.ld");

    fs::write(&generatedLinkerPath, generatedLinker)
        .expect("failed to write generated linker script");

    let manifestDirectory = manifestPath
        .parent()
        .expect("Cargo.toml has no parent directory");
    let linkerDirectory = manifestDirectory.join("linkers");

    println!("cargo:rerun-if-changed={}", manifestPath.display());
    println!(
        "cargo:rerun-if-changed={}",
        linkerDirectory.join("RP2040.ld").display()
    );
    println!(
        "cargo:rerun-if-changed={}",
        manifestDirectory
            .join("src/Native/Boot/RP2040/boot2.bin")
            .display()
    );

    println!("cargo:rustc-link-search=native={}", outDirectory.display());
    println!(
        "cargo:rustc-link-search=native={}",
        linkerDirectory.display()
    );
    println!("cargo:rustc-link-arg-bin=kernel=-Tpico-os.ld");
}
