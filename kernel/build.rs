use std::env;
use std::fs;
use std::path::PathBuf;

use toml::Value;

const FLASH_ORIGIN: u64 = 0x1000_0000;

fn positive_integer(root: &Value, path: &[&str]) -> u64 {
    let path_name = path.join(".");
    let mut value = root;

    for key in path {
        value = value
            .get(*key)
            .unwrap_or_else(|| panic!("missing Cargo.toml field `{path_name}`"));
    }

    let value = value
        .as_integer()
        .unwrap_or_else(|| panic!("`{path_name}` must be an integer"));

    u64::try_from(value)
        .ok()
        .filter(|value| *value != 0)
        .unwrap_or_else(|| panic!("`{path_name}` must be positive"))
}

fn main() {
    if env::var_os("CARGO_FEATURE_RP2040").is_none() {
        panic!("enable the RP2040 feature");
    }

    let target = env::var("TARGET").expect("Cargo did not provide TARGET");
    if target != "thumbv6m-none-eabi" {
        panic!("RP2040 requires target thumbv6m-none-eabi");
    }

    let manifest_path = PathBuf::from(
        env::var_os("CARGO_MANIFEST_PATH").expect("Cargo did not provide CARGO_MANIFEST_PATH"),
    );

    let manifest_text = fs::read_to_string(&manifest_path).expect("failed to read Cargo.toml");
    let manifest: Value = manifest_text.parse().expect("failed to parse Cargo.toml");

    let flash_mib = positive_integer(
        &manifest,
        &["package", "metadata", "pico-os", "flash-size-mb"],
    );
    let user_flash_kib = positive_integer(
        &manifest,
        &["package", "metadata", "pico-os", "user-flash-size-kb"],
    );

    let flash_bytes = flash_mib
        .checked_mul(1024 * 1024)
        .expect("flash size overflow");
    let user_flash_bytes = user_flash_kib
        .checked_mul(1024)
        .expect("user flash size overflow");

    assert!(
        user_flash_bytes >= 256 && user_flash_bytes.is_power_of_two(),
        "user flash size must be a power of two and at least 256 bytes"
    );
    assert!(
        user_flash_bytes < flash_bytes,
        "user flash must be smaller than physical flash"
    );

    let flash_end = FLASH_ORIGIN
        .checked_add(flash_bytes)
        .expect("flash address overflow");
    let user_flash_origin = flash_end - user_flash_bytes;

    assert!(
        user_flash_origin & (user_flash_bytes - 1) == 0,
        "user flash origin is not aligned to its MPU region size"
    );

    let kernel_flash_bytes = user_flash_origin - FLASH_ORIGIN;

    let generated_linker = format!(
        r#"/* Generated by build.rs. Do not edit. */
MEMORY
{{
    FLASH(rx)      : ORIGIN = 0x{FLASH_ORIGIN:08x}, LENGTH = 0x{kernel_flash_bytes:x}
    USER_FLASH(rx) : ORIGIN = 0x{user_flash_origin:08x}, LENGTH = 0x{user_flash_bytes:x}
    RAM(rwx)       : ORIGIN = 0x20000000, LENGTH = 256K
    SCRATCH_X(rwx) : ORIGIN = 0x20040000, LENGTH = 4K
    SCRATCH_Y(rwx) : ORIGIN = 0x20041000, LENGTH = 4K
}}

__flash_start = 0x{FLASH_ORIGIN:08x};
__flash_end = 0x{flash_end:08x};
__user_flash_start = ORIGIN(USER_FLASH);
__user_flash_end = ORIGIN(USER_FLASH) + LENGTH(USER_FLASH);

INCLUDE RP2040.ld
"#
    );

    let out_directory =
        PathBuf::from(env::var_os("OUT_DIR").expect("Cargo did not provide OUT_DIR"));
    let generated_linker_path = out_directory.join("pico-os.ld");

    fs::write(&generated_linker_path, generated_linker)
        .expect("failed to write generated linker script");

    let manifest_directory = manifest_path
        .parent()
        .expect("Cargo.toml has no parent directory");
    let linker_directory = manifest_directory.join("linkers");

    println!("cargo:rerun-if-changed={}", manifest_path.display());
    println!(
        "cargo:rerun-if-changed={}",
        linker_directory.join("RP2040.ld").display()
    );
    println!(
        "cargo:rerun-if-changed={}",
        manifest_directory
            .join("src/native/boot/rp2040/boot2.bin")
            .display()
    );

    println!("cargo:rustc-link-search=native={}", out_directory.display());
    println!(
        "cargo:rustc-link-search=native={}",
        linker_directory.display()
    );
    println!("cargo:rustc-link-arg-bin=kernel=-Tpico-os.ld");
}
